class Storage:
    """
    데이터를 파일에 저장하고 불러오는 역할을 담당하는 클래스입니다.

    이 프로그램에서는 state.json 파일을 관리합니다.

    주요 역할
    ------------------------------------------------------------
    - JSON 파일 읽기
    - JSON 파일 저장
    - 백업 파일 생성
    - 백업 파일 확인
    - 손상된 파일 복구
    """

    # --------------------------------------------------------
    # __init__() 메서드
    # --------------------------------------------------------

    def __init__(self, file_path):
        """
        Storage 객체를 생성합니다.

        매개변수
        --------------------------------------------------------
        file_path
            저장할 JSON 파일의 경로입니다.
        """

        # ----------------------------------------------------
        # Path 객체로 변환
        # ----------------------------------------------------
        # 전달받은 파일 경로를 Path 객체로 변환합니다.
        #
        # 예:
        #
        # "state.json"
        #
        # ↓
        #
        # Path("state.json")

        self.file_path = Path(file_path)

        # ----------------------------------------------------
        # 백업 파일 경로
        # ----------------------------------------------------
        # state.json
        #
        # 을
        #
        # state.json.bak
        #
        # 으로 만들어 저장합니다.
        #
        # self.file_path.suffix
        #
        # → ".json"
        #
        # ".json" + ".bak"
        #
        # → ".json.bak"

        self.backup_file_path = self.file_path.with_suffix(
            self.file_path.suffix + ".bak"
        )

    # --------------------------------------------------------
    # _load_file() 메서드
    # --------------------------------------------------------

    def _load_file(self, file_path):
        """
        지정된 JSON 파일 하나를 읽습니다.

        그리고 읽어온 데이터가
        프로그램에서 사용할 수 있는 올바른 형태인지 검사합니다.

        이름 앞에 _가 붙은 메서드는
        일반적으로 "클래스 내부에서 사용하는 메서드"라는 의미로
        사용하는 경우가 많습니다.
        """

        # ----------------------------------------------------
        # 파일 열기
        # ----------------------------------------------------
        # with 문을 사용하면 파일을 사용한 뒤
        # 자동으로 파일을 닫아줍니다.
        #
        # "r"
        # → read
        # → 읽기 모드
        #
        # encoding="utf-8"
        # → 한글을 정상적으로 읽기 위한 설정

        with file_path.open(
            "r",
            encoding="utf-8"
        ) as file:

            # ------------------------------------------------
            # JSON 읽기
            # ------------------------------------------------
            # json.load(file)
            #
            # JSON 파일의 내용을 읽어서
            # Python 자료형으로 변환합니다.
            #
            # JSON 객체
            # ↓
            # Python 딕셔너리
            #
            # JSON 배열
            # ↓
            # Python 리스트

            data = json.load(file)

        # ----------------------------------------------------
        # 데이터가 딕셔너리인지 확인
        # ----------------------------------------------------

        if not isinstance(data, dict):

            raise ValueError(
                "데이터 형식이 올바르지 않습니다."
            )

        # ----------------------------------------------------
        # 필수 데이터 확인
        # ----------------------------------------------------
        # 프로그램을 실행하려면
        #
        # "quizzes"
        # "best_score"
        #
        # 두 데이터가 반드시 있어야 합니다.

        if "quizzes" not in data or "best_score" not in data:

            raise ValueError(
                "필수 데이터가 없습니다."
            )

        # ----------------------------------------------------
        # quizzes가 리스트인지 확인
        # ----------------------------------------------------

        if not isinstance(data["quizzes"], list):

            raise ValueError(
                "퀴즈 데이터가 올바르지 않습니다."
            )

        # ----------------------------------------------------
        # best_score가 정수인지 확인
        # ----------------------------------------------------

        if not isinstance(data["best_score"], int):

            raise ValueError(
                "최고 점수 데이터가 올바르지 않습니다."
            )

        # 모든 검사를 통과했다면
        # 정상적인 데이터를 반환합니다.

        return data

    # --------------------------------------------------------
    # _get_backup_files() 메서드
    # --------------------------------------------------------

    def _get_backup_files(self):
        """
        사용할 수 있는 백업 파일 목록을 가져옵니다.

        백업 파일에는 두 종류가 있습니다.

        1. state.json.bak

        2. state.json.YYYYMMDD_HHMMSS.bak

        그리고 파일의 수정 시간을 기준으로
        최신 백업부터 정렬해서 반환합니다.
        """

        # 백업 파일들을 저장할 빈 리스트를 만듭니다.

        backup_files = []

        # ----------------------------------------------------
        # 일반 백업 파일 확인
        # ----------------------------------------------------

        if self.backup_file_path.exists():

            backup_files.append(
                self.backup_file_path
            )

        # ----------------------------------------------------
        # 시간 정보가 들어간 백업 파일 찾기
        # ----------------------------------------------------
        #
        # 예:
        #
        # state.json.20260816_101500.bak
        #
        # state.json.20260816_102000.bak
        #
        # 등을 찾습니다.

        timestamp_backups = self.file_path.parent.glob(
            f"{self.file_path.name}.*.bak"
        )

        # 찾은 파일들을 리스트에 추가합니다.

        backup_files.extend(
            timestamp_backups
        )

        # ----------------------------------------------------
        # 최신 파일부터 정렬
        # ----------------------------------------------------
        #
        # path.stat().st_mtime
        #
        # 은 파일이 마지막으로 수정된 시간을 의미합니다.
        #
        # reverse=True
        #
        # 를 사용하면 큰 값부터 정렬합니다.
        #
        # 즉, 최신 파일이 먼저 나옵니다.

        return sorted(
            backup_files,
            key=lambda path: path.stat().st_mtime,
            reverse=True
        )

    # --------------------------------------------------------
    # _restore_from_backup() 메서드
    # --------------------------------------------------------

    def _restore_from_backup(self):
        """
        백업 파일을 이용하여 state.json을 복구합니다.

        최신 백업 파일부터 하나씩 확인합니다.

        정상적인 백업을 찾으면
        state.json으로 복원합니다.

        사용할 수 있는 백업이 없으면
        None을 반환합니다.
        """

        # 백업 파일 목록을 가져옵니다.

        backup_files = self._get_backup_files()

        # 백업 파일을 하나씩 확인합니다.

        for backup_file in backup_files:

            try:

                # ------------------------------------------------
                # 백업 파일이 정상적인지 확인
                # ------------------------------------------------
                # 단순히 파일이 존재한다고 해서
                # 정상적인 파일이라는 보장은 없습니다.
                #
                # 따라서 _load_file()을 사용하여
                # JSON 형식과 데이터 구조를 확인합니다.

                data = self._load_file(
                    backup_file
                )

                # ------------------------------------------------
                # 정상적인 백업을 찾은 경우
                # ------------------------------------------------
                # backup_file.replace(self.file_path)
                #
                # 백업 파일을 state.json으로 이동시킵니다.
                #
                # 예:
                #
                # state.json.bak
                #
                # ↓
                #
                # state.json

                backup_file.replace(
                    self.file_path
                )

                print(
                    f"🔄 백업 파일을 이용해 데이터를 복원했습니다: "
                    f"{backup_file.name}"
                )

                # 복원된 데이터를 반환합니다.

                return data

            # ----------------------------------------------------
            # 백업 파일도 문제가 있는 경우
            # ----------------------------------------------------
            #
            # 하나의 백업 파일이 손상되었다고 해서
            # 프로그램을 종료하지 않습니다.
            #
            # 다음 백업 파일을 계속 확인합니다.

            except (
                json.JSONDecodeError,
                ValueError,
                KeyError,
                TypeError,
                OSError
            ):

                continue

        # 사용할 수 있는 백업이 없으면
        # None을 반환합니다.

        return None

    # --------------------------------------------------------
    # load() 메서드
    # --------------------------------------------------------

    def load(self):
        """
        state.json 파일을 불러옵니다.

        처리 순서
        --------------------------------------------------------
        1. state.json이 존재하는지 확인
        2. 존재하면 읽기
        3. 손상되었다면 백업 확인
        4. 백업도 없다면 None 반환
        """

        # ----------------------------------------------------
        # state.json이 존재하지 않는 경우
        # ----------------------------------------------------

        if not self.file_path.exists():

            print(
                "📂 state.json이 없습니다. "
                "백업 파일을 확인합니다."
            )

            # 백업 파일을 이용한 복구 시도

            restored_data = self._restore_from_backup()

            # 복구에 성공했다면
            # 복구된 데이터를 반환합니다.

            if restored_data is not None:
                return restored_data

            # 복구할 백업도 없다면
            # None을 반환합니다.
            #
            # 이후 QuizGame에서는
            # 기본 퀴즈를 사용하게 됩니다.

            print(
                "📂 사용할 수 있는 백업도 없습니다. "
                "기본 퀴즈를 사용합니다."
            )

            return None

        # ----------------------------------------------------
        # state.json이 존재하는 경우
        # ----------------------------------------------------

        try:

            # state.json을 읽습니다.

            data = self._load_file(
                self.file_path
            )

            # 정상적으로 읽었다면
            # 데이터를 반환합니다.

            return data

        # ----------------------------------------------------
        # JSON 파일이 손상된 경우
        # ----------------------------------------------------

        except (
            json.JSONDecodeError,
            ValueError,
            KeyError,
            TypeError
        ):

            print(
                "⚠️ state.json이 손상되었습니다."
            )

            print(
                "🔍 백업 파일을 이용한 복원을 시도합니다."
            )

            # 백업 파일 복구 시도

            restored_data = self._restore_from_backup()

            if restored_data is not None:
                return restored_data

            # 백업도 없다면 None 반환

            print(
                "⚠️ 복원 가능한 백업이 없습니다. "
                "기본 데이터로 초기화합니다."
            )

            return None

        # ----------------------------------------------------
        # 운영체제 수준의 파일 오류
        # ----------------------------------------------------
        # 예:
        # - 파일 접근 권한 문제
        # - 디스크 문제
        # - 파일 시스템 문제
        #
        # 등의 오류가 발생할 수 있습니다.

        except OSError as error:

            print(
                f"⚠️ 데이터 파일을 읽는 중 오류가 발생했습니다: "
                f"{error}"
            )

            print(
                "🔍 백업 파일을 이용한 복원을 시도합니다."
            )

            # 백업 파일 복구 시도

            restored_data = self._restore_from_backup()

            if restored_data is not None:
                return restored_data

            return None

    # --------------------------------------------------------
    # save() 메서드
    # --------------------------------------------------------

    def save(self, quizzes, best_score):
        """
        퀴즈 목록과 최고 점수를 JSON 파일에 저장합니다.

        저장하기 전에 기존 state.json을 백업합니다.

        백업 파일
        --------------------------------------------------------
        state.json.bak

        state.json.YYYYMMDD_HHMMSS.bak
        """

        # ----------------------------------------------------
        # 저장할 데이터 만들기
        # ----------------------------------------------------
        #
        # quizzes에는 Quiz 객체들이 들어 있습니다.
        #
        # JSON은 Quiz 객체를 직접 저장할 수 없으므로
        # Quiz 객체를 to_dict()를 이용해
        # 딕셔너리로 변환합니다.

        data = {
            "quizzes": [
                quiz.to_dict()
                for quiz in quizzes
            ],
            "best_score": best_score,
        }

        # ----------------------------------------------------
        # 파일 저장 과정에서 오류가 발생할 수 있으므로
        # try/except를 사용합니다.
        # ----------------------------------------------------

        try:

            # ------------------------------------------------
            # 기존 state.json 백업
            # ------------------------------------------------

            if self.file_path.exists():

                # shutil은 파일 복사 등에 사용하는
                # Python 표준 라이브러리입니다.
                #
                # 여기서는 save() 메서드 안에서
                # 필요할 때만 import합니다.

                import shutil

                # ------------------------------------------------
                # state.json.bak 생성
                # ------------------------------------------------
                #
                # 기존 state.json을
                # state.json.bak으로 복사합니다.

                shutil.copy2(
                    self.file_path,
                    self.backup_file_path
                )

                # ------------------------------------------------
                # 시간 정보가 들어간 백업 생성
                # ------------------------------------------------
                #
                # 현재 날짜와 시간을 문자열로 만듭니다.
                #
                # 예:
                #
                # 20260816_102530

                timestamp = datetime.now().strftime(
                    "%Y%m%d_%H%M%S"
                )

                # ------------------------------------------------
                # 백업 파일 경로 생성
                # ------------------------------------------------
                #
                # 예:
                #
                # state.json.20260816_102530.bak

                timestamp_backup = self.file_path.parent / (
                    f"{self.file_path.name}."
                    f"{timestamp}.bak"
                )

                # 기존 state.json을
                # 시간 정보가 들어간 백업 파일로 복사합니다.

                shutil.copy2(
                    self.file_path,
                    timestamp_backup
                )

                print(
                    f"💾 백업 생성: "
                    f"{timestamp_backup.name}"
                )

            # ------------------------------------------------
            # 새로운 state.json 저장
            # ------------------------------------------------

            with self.file_path.open(
                "w",
                encoding="utf-8"
            ) as file:

                # json.dump()
                #
                # Python 데이터를 JSON 형식으로
                # 파일에 저장합니다.
                #
                # ensure_ascii=False
                #
                # 한글이 \uXXXX 형태로 바뀌지 않고
                # 그대로 저장되도록 합니다.
                #
                # indent=4
                #
                # JSON 파일을 보기 좋게 들여쓰기합니다.

                json.dump(
                    data,
                    file,
                    ensure_ascii=False,
                    indent=4
                )

        # ----------------------------------------------------
        # 파일 저장 중 오류 처리
        # ----------------------------------------------------

        except OSError as error:

            print(
                f"⚠️ 데이터를 저장하는 중 오류가 발생했습니다: "
                f"{error}"
            )


