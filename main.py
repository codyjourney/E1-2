# 5. main() 함수
# ============================================================

def main():
    """
    프로그램의 시작점입니다.

    여기에서는 실제 게임에 필요한 객체를 만들고
    게임을 실행합니다.
    """

    # --------------------------------------------------------
    # 현재 Python 파일이 있는 폴더 찾기
    # --------------------------------------------------------
    #
    # __file__
    #
    # 현재 실행 중인 Python 파일의 경로입니다.
    #
    # 예:
    #
    # /home/user/quiz/main.py
    #
    # Path(__file__)
    #
    # 위 경로를 Path 객체로 변환합니다.
    #
    # .resolve()
    #
    # 절대 경로로 변환합니다.
    #
    # .parent
    #
    # 파일이 들어 있는 폴더를 가져옵니다.

    base_dir = Path(
        __file__
    ).resolve().parent

    # --------------------------------------------------------
    # state.json 경로 만들기
    # --------------------------------------------------------
    #
    # base_dir이
    #
    # /home/user/quiz
    #
    # 라면
    #
    # base_dir / "state.json"
    #
    # 결과는
    #
    # /home/user/quiz/state.json
    #
    # 이 됩니다.

    state_file = (
        base_dir / "state.json"
    )

    # --------------------------------------------------------
    # Storage 객체 생성
    # --------------------------------------------------------
    #
    # state.json 파일을 관리할 Storage 객체를 만듭니다.

    storage = Storage(
        state_file
    )

    # --------------------------------------------------------
    # QuizGame 객체 생성
    # --------------------------------------------------------
    #
    # storage 객체를 QuizGame에 전달합니다.
    #
    # QuizGame의 __init__()이 실행되면서
    # 내부적으로 load_data()가 실행됩니다.

    game = QuizGame(
        storage
    )

    # ========================================================
    # 게임 실행
    # ========================================================
    #
    # 프로그램 실행 중 발생할 수 있는
    # KeyboardInterrupt와 EOFError를 처리합니다.

    try:

        # 실제 게임 실행

        game.run()

    # --------------------------------------------------------
    # Ctrl+C 처리
    # --------------------------------------------------------
    #
    # 사용자가 Ctrl+C를 누르면
    # KeyboardInterrupt가 발생합니다.
    #
    # 프로그램이 갑자기 종료되지 않도록
    # 데이터를 저장한 후 종료합니다.

    except KeyboardInterrupt:

        print(
            "\n\n⚠️ Ctrl+C가 입력되었습니다."
        )

        print(
            "💾 현재 데이터를 저장하고 "
            "안전하게 종료합니다."
        )

        # 현재 게임 데이터를 저장합니다.

        game.save_data()

    # --------------------------------------------------------
    # EOFError 처리
    # --------------------------------------------------------
    #
    # 입력 스트림이 종료되면 발생할 수 있습니다.
    #
    # 예:
    #
    # 터미널에서 Ctrl+D
    #
    # 등의 상황에서 발생할 수 있습니다.

    except EOFError:

        print(
            "\n\n⚠️ 입력 스트림이 종료되었습니다."
        )

        print(
            "💾 현재 데이터를 저장하고 "
            "안전하게 종료합니다."
        )

        # 현재 데이터를 저장합니다.

        game.save_data()


# ============================================================
