    def get_number(
        self,
        prompt,
        min_value,
        max_value
    ):
        """
        사용자에게 숫자를 입력받습니다.

        입력값이 지정된 범위에 들어올 때까지
        계속 입력을 요청합니다.

        예:

        get_number("선택: ", 1, 5)

        → 1~5 사이의 숫자만 허용
        """

        # 올바른 입력이 들어올 때까지
        # 계속 반복합니다.

        while True:

            try:

                # ------------------------------------------------
                # 사용자 입력
                # ------------------------------------------------
                #
                # input()은 항상 문자열을 반환합니다.
                #
                # 예:
                #
                # 사용자가 3 입력
                #
                # 실제 값:
                #
                # "3"
                #
                # strip()은 앞뒤 공백을 제거합니다.

                user_input = input(
                    prompt
                ).strip()

                # ------------------------------------------------
                # 빈 입력 확인
                # ------------------------------------------------

                if not user_input:

                    print(
                        "⚠️ 입력값이 없습니다. "
                        "숫자를 입력해주세요."
                    )

                    # while문의 처음으로 돌아갑니다.

                    continue

                # ------------------------------------------------
                # 문자열 → 정수 변환
                # ------------------------------------------------
                #
                # input()은 문자열을 반환하기 때문에
                # 숫자로 사용하려면 int()가 필요합니다.
                #
                # "3"
                # ↓
                # 3

                number = int(
                    user_input
                )

                # ------------------------------------------------
                # 숫자 범위 확인
                # ------------------------------------------------

                if (
                    number < min_value
                    or number > max_value
                ):

                    print(
                        f"⚠️ {min_value}-{max_value} "
                        f"사이의 숫자를 입력해주세요."
                    )

                    # 잘못된 범위이므로 다시 입력받습니다.

                    continue

                # ------------------------------------------------
                # 정상적인 입력
                # ------------------------------------------------
                #
                # return을 만나면
                # 메서드가 종료되고 number 값을
                # 호출한 곳으로 돌려줍니다.

                return number

            # ----------------------------------------------------
            # 숫자로 변환할 수 없는 경우
            # ----------------------------------------------------
            #
            # 예:
            #
            # int("hello")
            #
            # 는 ValueError를 발생시킵니다.

            except ValueError:

                print(
                    "⚠️ 숫자만 입력해주세요."
                )

    # --------------------------------------------------------
