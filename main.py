    def get_non_empty_input(self, prompt):
        """
        사용자에게 문자열을 입력받습니다.

        단, 빈 문자열은 허용하지 않습니다.

        문제나 선택지를 입력할 때 사용합니다.
        """

        # 정상적인 입력이 들어올 때까지 반복합니다.

        while True:

            # 사용자 입력을 받고
            # 앞뒤 공백을 제거합니다.

            value = input(
                prompt
            ).strip()

            # ------------------------------------------------
            # 빈 문자열 확인
            # ------------------------------------------------

            if not value:

                print(
                    "⚠️ 빈 입력은 사용할 수 없습니다."
                )

                continue

            # 정상적인 문자열을 반환합니다.

            return value

    # --------------------------------------------------------
