    def play_quiz(self):
        """
        등록된 모든 퀴즈를 풀게 합니다.

        문제 순서는 랜덤으로 섞습니다.

        모든 문제를 푼 뒤
        정답 개수와 점수를 계산합니다.

        최고 점수보다 높은 점수가 나오면
        최고 점수를 갱신하고 저장합니다.
        """

