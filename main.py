# ============================================================
#
# Python 파일을 직접 실행했을 때만
# main() 함수를 실행합니다.
#
# Python에는 __name__이라는 특별한 변수가 있습니다.
#
# 이 파일을 직접 실행하면:
#
# __name__ == "__main__"
#
# 이 됩니다.
#
# 따라서 아래 코드가 실행됩니다.
#
# 반대로 다른 Python 파일에서
#
# import main
#
# 과 같이 가져오면
#
# __name__
#
# 은 "__main__"이 아니기 때문에
# main()이 자동으로 실행되지 않습니다.
