class Quiz:
    """
    하나의 퀴즈 문제를 표현하는 클래스입니다.

    Quiz 객체 하나는 다음 세 가지 정보를 가지고 있습니다.

    question
        퀴즈 문제 내용

    choices
        선택지 목록

    answer
        정답 번호

    예:
        Quiz(
            "Python에서 문자열 자료형은?",
            ["str", "int", "list", "bool"],
            1
        )

    위와 같이 만들면 하나의 Quiz 객체가 생성됩니다.
    """

    # --------------------------------------------------------
    # __init__() 메서드
    # --------------------------------------------------------

    def __init__(self, question, choices, answer):
        """
        Quiz 객체가 생성될 때 자동으로 실행되는 메서드입니다.

        __init__()은 객체의 초기 상태를 설정하는 역할을 합니다.

        매개변수
        --------------------------------------------------------
        question
            문제 내용입니다.

        choices
            선택지를 저장한 리스트입니다.

        answer
            정답 번호입니다.
            1~4 중 하나의 숫자를 저장합니다.
        """

        # ----------------------------------------------------
        # self.question
        # ----------------------------------------------------
        # 현재 생성되는 Quiz 객체의 question 변수에
        # 전달받은 question 값을 저장합니다.
        #
        # self는 "현재 객체 자신"을 의미합니다.
        #
        # 예:
        #
        # quiz = Quiz("문제", ["A", "B"], 1)
        #
        # 이때
        #
        # quiz.question
        #
        # 은 "문제"가 됩니다.

        self.question = question

        # 현재 Quiz 객체의 선택지를 저장합니다.
        #
        # 예:
        #
        # self.choices
        #
        # → ["str", "int", "list", "bool"]

        self.choices = choices

        # 현재 Quiz 객체의 정답 번호를 저장합니다.
        #
        # 예:
        #
        # self.answer
        #
        # → 1

        self.answer = answer

    # --------------------------------------------------------
    # display() 메서드
    # --------------------------------------------------------

    def display(self, number=None):
        """
        퀴즈 문제와 선택지를 화면에 출력합니다.

        number가 전달되면
        [문제 1], [문제 2]와 같이 문제 번호도 출력합니다.

        매개변수
        --------------------------------------------------------
        number
            문제 번호입니다.
            기본값은 None입니다.

        None
            "아직 값이 없다" 또는
            "값을 전달하지 않았다"는 의미로 자주 사용합니다.
        """

        # ----------------------------------------------------
        # 문제 번호 출력
        # ----------------------------------------------------
        # number가 None이 아니라면
        # 문제 번호를 출력합니다.
        #
        # 예:
        #
        # number = 1
        #
        # → [문제 1]

        if number is not None:
            print(f"\n[문제 {number}]")

        # ----------------------------------------------------
        # 문제 출력
        # ----------------------------------------------------
        # self.question에는 현재 Quiz 객체의
        # 문제 내용이 저장되어 있습니다.

        print(self.question)

        # ----------------------------------------------------
        # 선택지 출력
        # ----------------------------------------------------
        # enumerate()는 리스트의 값과 순서 번호를
        # 동시에 가져올 때 사용하는 함수입니다.
        #
        # start=1을 사용하면
        # 번호를 0부터 시작하지 않고 1부터 시작합니다.
        #
        # 예:
        #
        # choices = ["str", "int", "list", "bool"]
        #
        # enumerate(choices, start=1)
        #
        # 결과:
        #
        # 1, "str"
        # 2, "int"
        # 3, "list"
        # 4, "bool"

        for index, choice in enumerate(
            self.choices,
            start=1
        ):

            print(f"{index}. {choice}")

    # --------------------------------------------------------
    # check_answer() 메서드
    # --------------------------------------------------------

    def check_answer(self, user_answer):
        """
        사용자가 입력한 답이 정답인지 확인합니다.

        매개변수
        --------------------------------------------------------
        user_answer
            사용자가 입력한 답 번호

        반환값
        --------------------------------------------------------
        True
            정답인 경우

        False
            오답인 경우
        """

        # ----------------------------------------------------
        # == 연산자
        # ----------------------------------------------------
        # 두 값이 같은지 비교합니다.
        #
        # 예:
        #
        # self.answer = 2
        # user_answer = 2
        #
        # 2 == 2
        #
        # 결과:
        #
        # True
        #
        # 만약
        #
        # 2 == 3
        #
        # 이라면 결과는 False입니다.

        return user_answer == self.answer

    # --------------------------------------------------------
    # to_dict() 메서드
    # --------------------------------------------------------

    def to_dict(self):
        """
        Quiz 객체를 딕셔너리로 변환합니다.

        Python 객체 자체는 JSON에 바로 저장하기 어렵기 때문에
        JSON으로 저장하기 전에 딕셔너리 형태로 변환합니다.

        예:

        Quiz 객체
            ↓
        딕셔너리
            ↓
        JSON 파일

        """

        # 딕셔너리를 반환합니다.

        return {
            "question": self.question,
            "choices": self.choices,
            "answer": self.answer,
        }


